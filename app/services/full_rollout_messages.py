from __future__ import annotations


def employee_welcome_message() -> str:
    return (
        "你好，我是小律。你可以直接告诉我今天完成了什么、遇到什么问题、明天准备做什么，"
        "我会帮你整理成日报，并在你确认后提交；也可以随时查看、补充、修改、清空自己的日报，"
        "或查询个人、团队和部门的日报与工作总结。\n\n"
        "第一次见面，我想先问一下：以后怎么称呼你？你告诉我后，我可以把这个称呼记入你的"
        "个人记忆，之后按这个称呼和你交流；想修改或忘记时，直接告诉我就可以。"
    )


def management_query_notice() -> str:
    return """各位负责人好，小律日报系统现已支持日报查询和次日晨报，查询功能面向全员开放。

可以直接这样问：
1. “庞浩目前有多少份日报了？”——查询个人日报数量。
2. “总结下庞浩最近的工作。”——汇总个人近期工作。
3. “总结下法务一部本周/上周都做了什么？”——按团队和周期汇总工作。
4. “最近部门有什么重点需要关注？”——汇总问题、风险和重点计划。
5. “看下刘聪有什么没闭环的工作。”——查找计划中提过、但后续日报工作内容里再没出现的事项。

“未闭环”查询会把同一工作跨日重复计划合并为一项；如果后续日报写了“仍在推进”，会列为已有跟进，不会算作没有后续记录；如果计划后没有后续日报，会提示暂无法判断。该结果反映的是日报记录情况，不等同于认定实际工作一定未完成。

次日晨报将在每天 9:00 汇总上一工作日情况：
1. 团队负责人收到本团队的填报概览、未交人员、需关注事项、关键进展、后续计划和填报质量提示。
2. 中心负责人收到法务合约中心七个部门的整体填报情况、未交人员、跨团队重点事项、关键进展和后续计划。

所有查询均以系统当前已保存的日报为准。"""
